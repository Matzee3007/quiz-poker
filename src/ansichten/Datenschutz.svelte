    <h1>Datenschutz</h1>
    <p class="matt">
      Quiz-Poker ist eine private Seite für Spieleabende im Freundeskreis. Hier
      steht kurz, welche Daten dabei anfallen.
    </p>
  </section>
  <section class="karte stapel">
    <h2>Spielen ohne Konto</h2>
    <p class="matt">
      Namen, Einsätze und Antworten liegen nur im Spielraum. Er wird gelöscht,
      wenn der Quiz-Master ihn schließt oder 24 Stunden lang nichts passiert.
      Dein Browser speichert ein Token, damit du nach einem Abbruch
      zurückfindest, und den Entwurf eines Einmal-Quiz.
    </p>
  </section>
  <section class="karte stapel">
    <h2>Mit Konto</h2>
    <p class="matt">
      Gespeichert werden deine E-Mail-Adresse als Login-Name und dein Passwort
      als Hash, also nicht im Klartext. Ein Cookie hält dich 30 Tage angemeldet.
      Wenn du dein Konto löschst, sind diese Daten sofort entfernt.
    </p>
  </section>
  <section class="karte stapel">
    <h2>IP-Adressen</h2>
    <p class="matt">
      Beim Anmelden wird deine IP-Adresse gespeichert, um Fehlversuche zu
      begrenzen. Sie wird nach etwa einem Tag automatisch gelöscht.
    </p>
  </section>
  <section class="karte stapel">
    <h2>Hosting</h2>
    <p class="matt">
      Die Seite und ihre Daten liegen bei Cloudflare, das beim Ausliefern
      technisch bedingt auch IP-Adressen verarbeitet. Statistik- oder
      Werbedienste gibt es hier nicht.
    </p>
  </section>
  <section class="karte stapel">
    <h2>Fragen</h2>
    <p class="matt">
      Wende dich an den Betreiber, der dir die Einladung geschickt hat, oder an
      die Person, die deinen Spieleabend leitet.
    </p>
  </section>
